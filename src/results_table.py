"""Print the numbers shown in the two figures as Markdown tables (RESULTS.md).

Usage: python3 results_table.py <expected_csv> <races_csv> > RESULTS.md
"""
import csv
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("expected_figs", os.path.join(HERE, "expected_figs.py"))
figs = importlib.util.module_from_spec(spec)
spec.loader.exec_module(figs)

YEARS = [1994, 1998, 2002, 2006, 2010, 2014, 2018, 2022, 2026]


def pct(x):
    return f"{100 * (x - 1):+.1f}%".replace("-", "−")


def m(x):
    return f"{x / 1e6:.2f}"


def dm(act, exp):
    """actual minus expected in millions, rounded as in the figure labels (no "−0.00")"""
    d = round(act / 1e6 - exp / 1e6, 2) + 0.0
    return f"{d:+.2f}".replace("-", "−")


def main():
    E = list(csv.DictReader(open(sys.argv[1])))
    races = list(csv.DictReader(open(sys.argv[2])))
    ex = {(r["office"], int(r["year"])): r for r in E}
    offices = []
    for r in E:
        if (r["office"], r["title"]) not in offices:
            offices.append((r["office"], r["title"]))
    out = ["# Results", "",
           "Generated by `src/results_table.py` from `data/derived/`. Votes in millions unless marked. 2026 results "
           "are unofficial (Texas SOS, updated Nov. 4, 2026, 10:48 pm).", ""]

    out += ["## Presidential baselines (Texas, Republican and Democratic nominees)", "",
            "| Midterm | Presidential year | Republican | Democrat |", "|---|---|---:|---:|"]
    base = {}
    for r in E:
        base.setdefault(int(r["year"]), (int(r["pres_rep"]), int(r["pres_dem"])))
    for y, (pr, pd) in sorted(base.items()):
        out.append(f"| {y} | {y - 2} | {pr:,} | {pd:,} |")
    out.append("")

    out += ["## Left panels: midterm vote as % change from the party's presidential vote two years earlier", "",
            "R / D for each year. Avg = 1994–2022 average. The incumbency figure also shows the expected change for "
            "each year (next table).", ""]
    out.append("| Office | " + " | ".join(str(y) for y in YEARS) + " | Avg 1994–2022 |")
    out.append("|---|" + "---:|" * (len(YEARS) + 1))
    for key, title in offices:
        cells = []
        hist = [ex[(key, y)] for y in YEARS if (key, y) in ex and y <= 2022]
        for y in YEARS:
            r = ex.get((key, y))
            cells.append(f"{pct(float(r['ratio_rep']))} / {pct(float(r['ratio_dem']))}" if r else "no race")
        ar = sum(float(h["ratio_rep"]) for h in hist) / len(hist)
        ad = sum(float(h["ratio_dem"]) for h in hist) / len(hist)
        out.append(f"| {title} | " + " | ".join(cells) + f" | {pct(ar)} / {pct(ad)} |")
    out.append("")

    out += ["## Incumbency-adjusted expected change (shadow bars, left panel of the incumbency figure)", "",
            "Expected % change from the presidential vote, estimated without the year shown. President's party in "
            "brackets.", ""]
    out.append("| Office | " + " | ".join(f"{y} [{figs.PRES_PARTY[y]}]" for y in YEARS) + " |")
    out.append("|---|" + "---:|" * len(YEARS))
    for key, title in offices:
        cells = []
        for y in YEARS:
            r = ex.get((key, y))
            cells.append(f"{pct(float(r['expected_inc_rep']) / float(r['pres_rep']))} / "
                         f"{pct(float(r['expected_inc_dem']) / float(r['pres_dem']))}" if r else "no race")
        out.append(f"| {title} | " + " | ".join(cells) + " |")
    bs = {}
    for r in E:
        bs.setdefault(int(r["year"]), float(r["inc_b"]))
    out += ["", "In-party adjustment b (points of the presidential vote), by the year left out: " +
            ", ".join(f"{y}: {100 * b:+.1f}".replace("-", "−") for y, b in sorted(bs.items())) + ". Years 1994–2014 and 2026 use "
            "all of 1994–2022 except their own year (2026 uses all eight).", ""]

    summary = ["## Summary: actual minus expected, range across the races (millions of votes)", "",
               "| Expectation | Year | Races | Republican | Democrat |", "|---|---|---:|---:|---:|"]
    for inc, label in ((False, "plain"), (True, "president's party")):
        pre = "expected_inc_" if inc else "expected_"
        for y in (2018, 2022, 2026):
            rr = [r for r in races if int(r["year"]) == y]
            dr, dd = [], []
            for r in rr:
                e = ex[(figs.office_of(r["race_2026"]), y)]
                dr.append(round(float(r["rep_votes"]) / 1e6 - float(e[pre + "rep"]) / 1e6, 2) + 0.0)
                dd.append(round(float(r["dem_votes"]) / 1e6 - float(e[pre + "dem"]) / 1e6, 2) + 0.0)
            f = lambda v: f"{v:+.2f}".replace("-", "−")
            summary.append(f"| {label} | {y}{'*' if y == 2026 else ''} | {len(rr)} | {f(min(dr))} to {f(max(dr))} | "
                           f"{f(min(dd))} to {f(max(dd))} |")
    summary += ["", "2018 and 2022 rows count each race on the 2026 ballot once, so the court averages repeat "
                "(no U.S. Senate race in 2022).", ""]
    out[4:4] = summary
    for inc, label in ((False, "plain expectation"), (True, "adjusted for the president's party")):
        pre = "expected_inc_" if inc else "expected_"
        out += [f"## Right panels: actual vs. expected votes, {label}", "",
                "| Race | Year | R actual | R expected | R diff | D actual | D expected | D diff |",
                "|---|---|---:|---:|---:|---:|---:|---:|"]
        for r in races:
            y = int(r["year"])
            e = ex[(figs.office_of(r["race_2026"]), y)]
            ra, da = float(r["rep_votes"]), float(r["dem_votes"])
            re_, de = float(e[pre + "rep"]), float(e[pre + "dem"])
            out.append(f"| {r['race_2026']} | {y}{'*' if y == 2026 else ''} | {m(ra)} | {m(re_)} | {dm(ra, re_)} | "
                       f"{m(da)} | {m(de)} | {dm(da, de)} |")
        out.append("")
    out.append("\\* unofficial. Court rows for 2018 and 2022 are averages of that year's races for the same court; "
               "court rows use the court-wide expected vote.")
    print("\n".join(out))


if __name__ == "__main__":
    main()
